function tourPlay({
  id,
  type,
  text,
  shortText,
  description,
  down,
  spot,
  time,
  start,
  end,
  startSpot,
  endSpot,
  yards,
  scoring = false,
}) {
  return {
    id,
    typeSlug: type,
    typeText: type === 'rush' ? 'Rush' : 'Pass Reception',
    rawText: text,
    shortText,
    description,
    down,
    spot,
    quarter: '1st',
    time,
    clockDisplay: time,
    period: 1,
    team: AWAY.id,
    startYardLine: start,
    endYardLine: end,
    startDown: 1,
    startDistance: 10,
    endDown: 1,
    endDistance: 10,
    startPossessionText: startSpot,
    endPossessionText: endSpot,
    statYardage: yards,
    scoring,
  };
}

